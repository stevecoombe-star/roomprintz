-- PI-2: immutable AFC production generations, durable EMPTY/TILED reuse,
-- room-level current successful generation pointer, private AFC Storage,
-- and lineage-safe activation.
--
-- AFC generations are independent of vibode_generation_runs (2D compositor).
-- EMPTY/TILED are not stage_output assets.
-- Tables are fail-closed under RLS; production APIs use the service role
-- after owner authorization.
--
-- Storage privacy invariant (bucket vibode-afc-v2):
--   anon          → no access
--   authenticated → no list / select / upload / update / delete
--                   and cannot mint usable AFC object URLs
--   service_role → production persistence access
--
-- Ready-row authority remains immutable. DELETE is allowed so
-- vibode_rooms ON DELETE CASCADE and authorized cleanup can succeed.
-- Browser roles are not granted table DELETE.

