-- UPDATE immutability only. DELETE must succeed for room cascade / cleanup.
create or replace function public.vibode_afc_generations_protect_authority()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.lineage_seq is distinct from old.lineage_seq
    or new.room_id is distinct from old.room_id
    or new.user_id is distinct from old.user_id
    or new.run_id is distinct from old.run_id
  then
    raise exception 'AFC generation identity is immutable';
  end if;
  if old.status = 'ready' then
    if new.production_authority is distinct from old.production_authority
      or new.original_sha256 is distinct from old.original_sha256
      or new.empty_sha256 is distinct from old.empty_sha256
      or new.tiled_sha256 is distinct from old.tiled_sha256
      or new.frame_width is distinct from old.frame_width
      or new.frame_height is distinct from old.frame_height
      or new.intent is distinct from old.intent
    then
      raise exception 'AFC generation authority is immutable once ready';
    end if;
  end if;
  if old.status = 'failed' and new.status = 'ready' then
    raise exception 'AFC generation cannot be revived from failed to ready';
  end if;
  return new;
end;
$$;

drop trigger if exists vibode_afc_generations_protect_authority
  on public.vibode_afc_generations;

create trigger vibode_afc_generations_protect_authority
before update on public.vibode_afc_generations
for each row execute function public.vibode_afc_generations_protect_authority();

create or replace function public.protect_current_afc_generation_id()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'UPDATE'
    and new.current_afc_generation_id is distinct from old.current_afc_generation_id
    and auth.role() = 'authenticated'
  then
    raise exception 'current_afc_generation_id is server-managed';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_current_afc_generation_id
  on public.vibode_rooms;

create trigger protect_current_afc_generation_id
before update on public.vibode_rooms
for each row execute function public.protect_current_afc_generation_id();

-- Activate only when the candidate is newer than the current pointer.
-- Same generation is a no-op success. Older ready generations stay persisted
-- but do not become current.
create or replace function public.activate_vibode_afc_generation(
  p_room_id uuid,
  p_user_id uuid,
  p_generation_id uuid
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
  v_room uuid;
  v_user uuid;
  v_seq bigint;
  v_current uuid;
  v_current_seq bigint;
begin
  select r.current_afc_generation_id
    into v_current
  from public.vibode_rooms r
  where r.id = p_room_id
    and r.user_id = p_user_id
  for update;

  if not found then
    raise exception 'AFC room pointer update failed';
  end if;

  select g.status, g.room_id, g.user_id, g.lineage_seq
    into v_status, v_room, v_user, v_seq
  from public.vibode_afc_generations g
  where g.id = p_generation_id
  for update;

  if v_status is null then
    raise exception 'AFC generation not found';
  end if;
  if v_room is distinct from p_room_id or v_user is distinct from p_user_id then
    raise exception 'AFC generation does not belong to room owner';
  end if;
  if v_status is distinct from 'ready' then
    raise exception 'AFC generation is not production-ready';
  end if;

  if v_current is null or v_current = p_generation_id then
    update public.vibode_rooms
      set current_afc_generation_id = p_generation_id
    where id = p_room_id
      and user_id = p_user_id;
    return p_generation_id;
  end if;

  select g.lineage_seq
    into v_current_seq
  from public.vibode_afc_generations g
  where g.id = v_current
  for update;

  if v_current_seq is null or v_seq > v_current_seq then
    update public.vibode_rooms
      set current_afc_generation_id = p_generation_id
    where id = p_room_id
      and user_id = p_user_id;
    return p_generation_id;
  end if;

  return v_current;
end;
$$;

