-- Restrictive policies fail closed even if a dashboard policy later grants
-- authenticated access to "own folder" across buckets.
drop policy if exists vibode_afc_v2_deny_anon on storage.objects;
drop policy if exists vibode_afc_v2_deny_authenticated on storage.objects;

create policy vibode_afc_v2_deny_anon
on storage.objects
as restrictive
for all
to anon
using (bucket_id <> 'vibode-afc-v2')
with check (bucket_id <> 'vibode-afc-v2');

create policy vibode_afc_v2_deny_authenticated
on storage.objects
as restrictive
for all
to authenticated
using (bucket_id <> 'vibode-afc-v2')
with check (bucket_id <> 'vibode-afc-v2');

commit;
